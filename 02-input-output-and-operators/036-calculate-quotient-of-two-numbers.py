"""
Problem: Calculate Quotient of Two Numbers

Description:
Write a Python program that asks the user to enter two numbers, calculates the quotient of the 
first number divided by the second number, and displays the result.

Expected Interaction:
Enter first number: 20
Enter second number: 4
Quotient: 5.0
"""

num1 = int(input("Enter first number: "))

"""
Problem: Calculate Age in Days

Description:
Write a Python program that stores a person's age in years, converts the age into 
an approximate number of days, and displays the result.

Assumption:
1 year = 365 days

Formula:
Days = Age × 365

Expected Output:
Approximate age in days: 8760
"""

age = 24

days = age * 365

print(f"Approximate age in days: {days}")
"""
Problem: Calculate Remaining Amount

Description:
Write a Python program that stores a person's total amount of money and the amount spent in 
separate variables. Calculate and display the remaining amount.

Formula:
Remaining Amount = Total Amount - Amount Spent

Expected Output:
Remaining Amount: 3250
"""


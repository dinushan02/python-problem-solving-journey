"""
Problem: Convert Celsius to Fahrenheit

Description:
Write a Python program that stores a temperature in Celsius, converts it to 
Fahrenheit, and displays the result.

Formula:
Fahrenheit = (Celsius × 9 / 5) + 32

Expected Output:
Fahrenheit: 77.0
"""

celsius = 25

fahrenheit = (celsius * 9 / 5) + 32

print(f"Fahrenheit: {fahrenheit}")
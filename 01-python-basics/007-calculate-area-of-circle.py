"""
Problem: Calculate Area of a Circle

Description:
Write a Python program that stores the radius of a circle in a variable, 
calculates its area, and displays the result.

Formula:
Area = π × radius²

Expected Output:
Area: 78.5
"""

radius = 5

area = 3.14 * radius * radius
# area = 3.14 * radius ** 2

print(f"Area: {area}")
"""
Problem: Convert Fahrenheit to Celsius

Description:
Write a Python program that stores a temperature in Fahrenheit, converts it 
to Celsius, and displays the result.

Formula:
Celsius = (Fahrenheit - 32) × 5 / 9

Expected Output:
Celsius: 37.0
"""

fahrenheit = 98.6

celsius = (fahrenheit - 32) * 5 / 9

print(f"Celsius: {celsius}")
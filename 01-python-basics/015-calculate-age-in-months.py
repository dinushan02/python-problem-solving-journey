"""
Problem: Calculate Age in Months

Description:
Write a Python program that stores a person's age in years, converts the age into 
an approximate number of months, and displays the result.

Assumption:
1 year = 12 months

Formula:
Months = Age × 12

Expected Output:
Approximate age in months: 288
"""

age = 24

months = age * 12

print(f"Approximate age in months: {months}")